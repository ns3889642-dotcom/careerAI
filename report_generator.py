from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def generate_report(skills, result, recommendations):

    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        textColor=colors.HexColor("#4338CA"),
        alignment=TA_CENTER,
        fontSize=24
    )

    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#4338CA")
    )

    story = []

    # Title
    story.append(
        Paragraph("CareerAI - Resume Analysis Report", title_style)
    )

    story.append(Spacer(1, 20))

    # Skills
    story.append(
        Paragraph("1. Resume Skills", heading_style)
    )

    story.append(
        Paragraph(
            ", ".join(skills) if skills else "No skills detected",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 15))

    # Job Matching
    story.append(
        Paragraph("2. Job Matching Results", heading_style)
    )

    data = [
        ["Metric", "Score"],
        ["Skill Match", f"{result['match_score']}%"],
        ["Text Similarity", f"{result['similarity']}%"]
    ]

    table = Table(data, colWidths=[220, 220])

    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4338CA")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 10),
    ]))

    story.append(table)

    story.append(Spacer(1, 15))

    # Matched Skills
    story.append(
        Paragraph("3. Matched Skills", heading_style)
    )

    story.append(
        Paragraph(
            ", ".join(result["matched_skills"]) or "None",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 15))

    # Missing Skills
    story.append(
        Paragraph("4. Missing Skills", heading_style)
    )

    story.append(
        Paragraph(
            ", ".join(result["missing_skills"]) or "None",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 15))

    # Career Recommendations
    story.append(
        Paragraph("5. Career Recommendations", heading_style)
    )

    for item in recommendations:

        story.append(
            Paragraph(
                f"<b>{item['career']}</b> - "
                f"Skill Coverage: {item['score']}%",
                styles["BodyText"]
            )
        )

        story.append(Spacer(1, 8))

    story.append(Spacer(1, 20))

    story.append(
        Paragraph(
            "Generated by CareerAI | AI-Powered Career Guidance",
            styles["Italic"]
        )
    )

    doc.build(story)

    buffer.seek(0)

    return buffer.getvalue()